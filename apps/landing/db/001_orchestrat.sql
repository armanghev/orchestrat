create table if not exists public.orchestrat (
  id bigint generated by default as identity primary key,
  email text not null,
  created_at timestamptz not null default now(),
  constraint orchestrat_email_unique unique (email),
  constraint orchestrat_email_normalized check (email = lower(btrim(email)))
);

create unique index if not exists orchestrat_email_unique
  on public.orchestrat (email);
