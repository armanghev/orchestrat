// orchestrat init: prints a .env for deploy/compose.yml with fresh secrets.
//   docker compose run --rm --no-deps -T orchestrat init > .env
import { randomBytes } from "node:crypto";

const secret = (bytes: number) => randomBytes(bytes).toString("base64url");
const publicUrl = process.argv[2] ?? "http://localhost:8801";

try {
  new URL(publicUrl);
} catch {
  console.error(`Not a URL: ${publicUrl}`);
  process.exit(1);
}

process.stdout
  .write(`# Generated by \`orchestrat init\` on ${new Date().toISOString()}.
# Keep this file private: it holds the database password and the keys that
# encrypt Git provider tokens.

# Where people and agents reach this server.
ORCHESTRAT_PUBLIC_URL=${publicUrl}

# Postgres (the bundled postgres service uses it too).
POSTGRES_PASSWORD=${secret(24)}

# Needed to create the first (admin) account. The server also prints a
# setup link with it while there are no accounts.
ORCHESTRAT_SETUP_TOKEN=${secret(24)}

# Who may create accounts after the admin: invite | open | closed
ORCHESTRAT_SIGNUP=invite

# Encrypts GitHub/GitLab tokens at rest. Don't change it once in use.
ORCHESTRAT_REPOSITORY_SECRET_KEY=${randomBytes(32).toString("base64")}
ORCHESTRAT_REPOSITORY_SECRET_KEY_ID=k1

# Object storage for attachments (docker compose -f compose.yml -f
# compose.storage.yml up -d). Browsers upload straight to this endpoint, so it
# must be reachable from them.
S3_ACCESS_KEY=orchestrat
S3_SECRET_KEY=${secret(24)}
ORCHESTRAT_S3_PUBLIC_ENDPOINT=http://localhost:8333
`);
console.error(
  "Wrote a new .env. Next: docker compose up -d, then open the setup link from `docker compose logs orchestrat`."
);
